def head(ws, row, values, widths=None):
    for i, v in enumerate(values, start=1):
        c = ws.cell(row=row, column=i, value=v)
        c.fill, c.font, c.border = H_FILL, H_FONT, BOX
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
    ws.row_dimensions[row].height = 30
    if widths:
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(i)].width = w


def title(ws, row, text, span=6):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(bold=True, size=13, color="1F3864")
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    return row + 1


def note(ws, row, text, span=6, italic=True):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(italic=italic, size=9.5, color="595959")
    c.alignment = WRAP
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    return row + 1


