def h(text, level=1):
    doc.add_heading(text, level=level)


def p(text, bold=False, italic=False, size=None):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    return par


def bullets(items, style="List Bullet"):
    for it in items:
        doc.add_paragraph(it, style=style)


def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0].cells
    for i, text in enumerate(headers):
        hdr[i].text = ""
        run = hdr[i].paragraphs[0].add_run(text)
        run.bold = True
        run.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(val))
            run.font.size = Pt(9.5)
    if widths:
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
        # без явної ширини tblW=dxa LibreOffice/Word розтягують таблицю за вмістом
        tblW = t._tbl.tblPr.find(qn("w:tblW"))
        tblW.set(qn("w:type"), "dxa")
        tblW.set(qn("w:w"), str(int(round(sum(widths) * 566.929))))
    doc.add_paragraph()
    return t


